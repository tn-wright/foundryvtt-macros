function createCategoryContent(proverbArray) {
  let categoryContent = "";

  for (let i = 0; i < proverbArray.length; i++) {
    categoryContent += `<p><span style="font-weight:bold;">Option ${
      i + 1
    }:</span> "${proverbArray[i]}"</p>`;
  }

  return categoryContent;
}

const proverbDialog = new Dialog({
  title: "Proverb by Category",
  content: `
  <p>Choose which features to activate during your trance:</p><br>
  <form>
    <div class="form-group">
      <label for="category">Category</label>
      <select name="category">
        <option value="justice" selected >Judgment and Justice</option>
        <option value="faith" >Faith and Devotion</option>
        <option value="purpose" >Life and Purpose</option>
        <option value="undead" >The Undead and the Corrupt</option>
        <option value="strength" >Strength and Perseverance</option>
        <option value="wisdom" >Wisdom and Guidance</option>
        <option value="prayer" >Prayer and Worship</option>
        <option value="sin" >Sin and Redemption</option>
        <option value="plan" >The Divine Plan</option>
        <option value="unity" >Unity and Community</option>
      </select>
    </div>
  </form>
  `,
  buttons: {
    submit: {
      icon: "<i class='fa-solid fa-check'></i>",
      label: "Submit",
      callback: (html) => {
        const formData = new FormDataExtended(html[0].querySelector("form"))
          .object;

        const categoryName = formData.category;

        const categoryContent = createCategoryContent(
          proverbArrays[categoryName]
        );

        const whisperIds = [game.userId];
        const messageSpeaker = ChatMessage.getSpeaker(game.user.character);

        ChatMessage.create({
          content: categoryContent,
          speaker: messageSpeaker,
          whisper: whisperIds,
        });
      },
    },
    cancel: {
      icon: "<i class='fa-solid fa-xmark'></i>",
      label: "Cancel",
      callback: () => {
        return;
      },
    },
  },
});

proverbDialog.render(true);
